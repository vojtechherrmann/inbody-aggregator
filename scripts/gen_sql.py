"""Generate `.azure/sql/inbody_tables.sql` from the SQLAlchemy metadata (src/web/db.py), which
itself derives the measurement columns from the extraction package's field registry. One source
of truth for SQLite (tests, local) and Azure SQL; tests/web/test_schema_sync.py fails when the
committed file is stale.

    .venv/bin/python scripts/gen_sql.py            # rewrite the file
    .venv/bin/python scripts/gen_sql.py --check    # exit 1 if it is stale

003 is for a FRESH database (every statement is guarded, so re-running it is harmless, but it never
ALTERs an existing table). Once 003 has been applied to Azure, a registry change needs a new
numbered migration with the ALTERs -- regenerate 003 too, so a rebuilt database matches.
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src" / "web"))

import db  # noqa: E402
from sqlalchemy.dialects import mssql  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

TARGET = REPO / ".azure" / "sql" / "inbody_tables.sql"

HEADER = """-- GENERATED by scripts/gen_sql.py from src/web/db.py -- do not edit by hand.
-- Tables of inbody-aggregator in schema `inbody` (db `vojtah` on vhgwcsql1), for a fresh database.
-- The extraction / measurement columns come from the extraction package's field registry
-- (extraction/validate.py). Every statement is guarded, so re-running is harmless.
-- The app's MI has SELECT/INSERT/UPDATE/DELETE on the whole schema (002): no new grants needed.
--
-- The ACCOUNTS (vojtah.app_user, vojtah.user_session, vojtah.sso_ticket) are the site's and are
-- NOT created here: apply the site's vojtah_tables.sql first (the foreign keys below need them);
-- the app's grants on them are in inbody_grant_web.sql.
--
-- App STATE (not derivable): share, api_usage.
-- DERIVED from the raw files in blob (scripts/pipeline.py rebuild-index + reprocess):
--   upload, extraction, measurement, measurement_conflict.
-- measured_at_local is the LOCAL wall clock as printed/exported (never converted); the other
-- *_at columns are UTC.
"""


def render() -> str:
    dialect = mssql.dialect()
    out = [HEADER]
    for table in db.metadata.sorted_tables:
        if table.schema != db.SCHEMA:
            continue  # the site's accounts (schema vojtah): created by the site, not by this app
        ddl = str(CreateTable(table).compile(dialect=dialect)).strip()
        out.append(f"IF OBJECT_ID('{db.SCHEMA}.{table.name}', 'U') IS NULL\n{ddl};\nGO\n")
        for index in sorted(table.indexes, key=lambda i: i.name):
            idx = str(CreateIndex(index).compile(dialect=dialect)).strip()
            out.append(
                f"IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = '{index.name}'\n"
                f"               AND object_id = OBJECT_ID('{db.SCHEMA}.{table.name}'))\n"
                f"    {idx};\nGO\n"
            )
    return "\n".join(out)


def main() -> None:
    text = render()
    if "--check" in sys.argv:
        current = TARGET.read_text() if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET} is stale: run scripts/gen_sql.py")
            sys.exit(1)
        print("up to date")
        return
    TARGET.write_text(text)
    print(f"wrote {TARGET} ({text.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
